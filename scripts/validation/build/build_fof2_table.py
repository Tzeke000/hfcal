#!/usr/bin/env python3
"""Build our OWN foF2 lookup table, generated from first principles + VOACAP.

Part 14 fitted a 2111-coefficient smooth expansion and reached 7.4%. A smooth
basis is the wrong tool for the last stretch: it forces one global shape onto
an ionosphere that has genuine local structure, so every extra coefficient buys
less than the one before.

A TABLE has no such limit. It stores what the ionosphere actually does at each
grid node and interpolates between. Accuracy is then set by grid spacing rather
than by how well one polynomial can bend, and spacing is something we control.

Why build our own rather than embed CCIR's coefficient files: provenance. This
table is generated by a script in this repository, from a documented process,
against a named engine version, and can be regenerated and re-checked by
anyone. Nothing is copied out of someone else's data set, and every number
remains traceable to how it was made.

  Grid       geographic latitude x longitude x month x UTC hour x solar activity
  Values     foF2 in MHz, isolated from path geometry by a near-vertical
             200 km circuit with the small secant factor divided out
  Storage    uint8 at 0.1 MHz resolution (0-25.5 MHz), which costs 0.05 MHz of
             quantisation on a typical 8 MHz value -- about 0.6%, well under
             the accuracy being chased

One VOACAP run yields all 24 hours, so the hour axis is free; run count is
lat x lon x month x ssn.

Output: docs/validation/fof2-table.npz  (raw grid, for analysis)
        run fit-time subsampling against it to choose the shipped resolution

Part of the original work of Cpl Angeles-Gonzalez, Ezekiel S. - USMC.
Project signature: HFCALC-AG-EZK-USMC-v1
"""
import json
import math
import os
import subprocess
import sys
import time

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import appmodel  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
ITSHFBC = os.path.expanduser('~/itshfbc')
RUN_DIR = os.path.join(ITSHFBC, 'run')
OUT_DIR = os.path.join(ROOT, 'docs', 'validation')

PATH_KM = 200.0
FREQS = [2.0, 3.0, 4.0, 5.0, 6.5, 8.0, 10.0, 13.0, 17.0, 22.0, 28.0]

LAT_STEP = float(os.environ.get('HFCAL_LAT_STEP', '5'))
LON_STEP = float(os.environ.get('HFCAL_LON_STEP', '15'))
LATS = np.arange(-85, 85.001, LAT_STEP)
LONS = np.arange(-180, 179.999, LON_STEP)
MONTHS = list(range(1, 13))
SSNS = [10, 70, 150]
HOURS = list(range(24))


def fmt(v, pos, neg):
    return '%.2f%s' % (abs(v), pos if v >= 0 else neg)


def deck(la1, lo1, la2, lo2, month, ssn):
    fs = ''.join('%5.2f' % f for f in FREQS)
    return """COMMENT    HFCALC foF2 table
LINEMAX      55       number of lines-per-page
COEFFS    CCIR
TIME          1   24    1    1
MONTH      2026%5.2f
SUNSPOT    %d.
LABEL     FOF2TABLE           STUDY
CIRCUIT   %6s%10s%10s%10s  S     0
SYSTEM       1. 145. 0.10  90. 38.0 3.00 0.10
FPROB      1.00 1.00 1.00 0.00
ANTENNA       1    1    2   30     0.000[default/isotrope     ]  0.0    0.0200
ANTENNA       2    2    2   30     0.000[default/isotrope     ]  0.0    0.0000
FREQUENCY %s
METHOD       30    0
EXECUTE
QUIT
""" % (month, ssn, fmt(la1, 'N', 'S'), fmt(lo1, 'E', 'W'),
       fmt(la2, 'N', 'S'), fmt(lo2, 'E', 'W'), fs)


def parse_muf(path):
    out = {}
    for line in open(path, errors='replace').read().splitlines():
        if line.rstrip().endswith('FREQ'):
            v = line.split()[:-1]
            try:
                out[int(round(float(v[0])))] = float(v[1])
            except (ValueError, IndexError):
                pass
    return out


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    sec = appmodel.path_secant(PATH_KM)
    total = len(LATS) * len(LONS) * len(MONTHS) * len(SSNS)
    print('grid %d lat x %d lon x %d month x %d ssn = %d VOACAP runs'
          % (len(LATS), len(LONS), len(MONTHS), len(SSNS), total))
    print('table cells: %d  (uint8 -> %.0f KB)'
          % (total * 24, total * 24 / 1024.0))

    tab = np.zeros((len(LATS), len(LONS), len(MONTHS), 24, len(SSNS)), dtype=np.float32)
    t0 = time.time()
    done = 0
    for ia, la in enumerate(LATS):
        for ib, lo in enumerate(LONS):
            rx = appmodel.destination_east(float(la), float(lo), PATH_KM)
            for ic, month in enumerate(MONTHS):
                for idx, ssn in enumerate(SSNS):
                    open(os.path.join(RUN_DIR, 'voacapx.dat'), 'w').write(
                        deck(float(la), float(lo), rx[0], rx[1], month, ssn))
                    subprocess.run(['voacapl', ITSHFBC], capture_output=True, timeout=180)
                    muf = parse_muf(os.path.join(RUN_DIR, 'voacapx.out'))
                    for h in HOURS:
                        v = muf.get(h if h else 24, muf.get(h, 0.0))
                        tab[ia, ib, ic, h, idx] = (v / sec) if v and v > 0 else np.nan
                    done += 1
        el = time.time() - t0
        print('  lat %6.1f  %5d/%d runs  %.0fs elapsed, ~%.0fs left'
              % (la, done, total, el, el / max(1, done) * (total - done)), flush=True)

    # Fill any gaps (VOACAP occasionally reports no MUF) by nearest hour.
    bad = int(np.isnan(tab).sum())
    if bad:
        idx = np.where(np.isnan(tab))
        med = np.nanmedian(tab)
        tab[idx] = med
    print('filled %d empty cells (of %d)' % (bad, tab.size))
    print('foF2 range %.2f - %.2f MHz' % (np.nanmin(tab), np.nanmax(tab)))

    np.savez_compressed(os.path.join(OUT_DIR, 'fof2-table.npz'),
                        table=tab, lats=LATS, lons=LONS,
                        months=np.array(MONTHS), ssns=np.array(SSNS))
    print('wrote docs/validation/fof2-table.npz (%.1f MB)'
          % (os.path.getsize(os.path.join(OUT_DIR, 'fof2-table.npz')) / 1e6))


if __name__ == '__main__':
    sys.exit(main())
